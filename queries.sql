-- Задание 5. Все заказы
SELECT id, дата, клиент, товар_id, количество FROM Заказ;

-- Задание 6. Заказы конкретного клиента
SELECT id, дата, товар_id, количество
FROM Заказ
WHERE клиент = 'Иванов Иван Иванович';

-- Задание 7. JOIN — заказы с названиями товаров
SELECT Заказ.дата, Заказ.клиент, Товар.марка, Товар.модель, Заказ.количество
FROM Заказ
JOIN Товар ON Заказ.товар_id = Товар.id;

-- Задание 8. Общая сумма всех заказов
SELECT SUM(Товар.цена * Заказ.количество) AS Итого
FROM Заказ
JOIN Товар ON Заказ.товар_id = Товар.id;

-- Задание 9. Количество заказов по клиентам
SELECT клиент, COUNT(*) AS Количество_заказов
FROM Заказ
GROUP BY клиент;

-- Задание 10. Мой запрос
-- Что хочу получить: список автомобилей дороже 3 000 000 руб.,
-- отсортированный по убыванию цены, с указанием марки, модели и цены.
SELECT марка, модель, цена
FROM Товар
WHERE цена > 3000000
ORDER BY цена DESC;