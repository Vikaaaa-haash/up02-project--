-- Задание 1. Самый дорогой автомобиль
SELECT марка, модель, цена FROM Товар ORDER BY цена DESC LIMIT 1;

-- Задание 2. Самый дешёвый автомобиль
SELECT марка, модель, цена FROM Товар ORDER BY цена ASC LIMIT 1;

-- Задание 3. Автомобили одной марки (категории)
-- Категория = марка. Возьмём Toyota.
